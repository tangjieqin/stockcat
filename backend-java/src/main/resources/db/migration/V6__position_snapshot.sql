-- P1.5 持仓快照：由 trade_record 重放 + 当日收盘价生成，不是第二事实来源。
-- 任何一天都可以按流水全量重建；重建 = 先删区间再插，不做增量修补。
CREATE TABLE position_snapshot (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_date       DATE           NOT NULL,
    instrument_id    BIGINT         NOT NULL REFERENCES instrument(id),
    quantity         NUMERIC(24, 4) NOT NULL,
    avg_cost         NUMERIC(20, 6) NOT NULL,
    -- 持仓成本 = quantity × avg_cost，落库是为了聚合时不必再乘一遍（也避免各处舍入不一致）
    cost_value       NUMERIC(24, 4) NOT NULL,
    close_price      NUMERIC(20, 6),
    market_value     NUMERIC(24, 4),
    unrealized_pnl   NUMERIC(24, 4),
    -- 截至当日累计已实现盈亏（不是当日发生额），口径见 docs/DATABASE.md
    realized_pnl_cum NUMERIC(24, 4) NOT NULL DEFAULT 0,
    -- 实际取价口径：raw（默认，能与成交价直接比较）/ qfq（兜底，见服务层注释）
    price_adjust     VARCHAR(8)     NOT NULL,
    source_code      VARCHAR(32),
    created_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uq_position_snapshot UNIQUE (trade_date, instrument_id),
    CONSTRAINT ck_position_snapshot_qty CHECK (quantity >= 0),
    CONSTRAINT ck_position_snapshot_close CHECK (close_price IS NULL OR close_price > 0)
);
CREATE INDEX idx_position_snapshot_date ON position_snapshot (trade_date DESC);

COMMENT ON TABLE position_snapshot IS '每日持仓快照（P1.5）；由 trade_record 重放 + 收盘价生成，可随时全量重建';
COMMENT ON COLUMN position_snapshot.cost_value IS '持仓成本 = quantity × avg_cost（avg_cost 已含买入费用）';
COMMENT ON COLUMN position_snapshot.close_price IS '当日收盘价；取不到时留 null，market_value/unrealized_pnl 一并留 null，不按 0 计算';
COMMENT ON COLUMN position_snapshot.realized_pnl_cum IS '截至当日累计已实现盈亏（摊薄成本法，已扣卖出费用）';
COMMENT ON COLUMN position_snapshot.price_adjust IS '收盘价复权口径；raw 才能与成交价直接相减';
