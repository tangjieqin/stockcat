-- P1.4 基金参考数据（ETF/LOF 的 IOPV 与单位净值）
--
-- 语义：一行 = 一个基金在一个交易日的观测，不是「净值历史表」。
--   trade_date  行情日期（盘中取自数据源时间；净值补写行为净值日期）
--   iopv        参考净值，仅 ETF 有；盘中每 15 秒刷新
--   nav         单位净值，来自天天基金 f10/lsjz（带日期，权威）
--   nav_date    净值所属日期；与 trade_date 不同即说明基准滞后（LOF 盘中必然 T-1）
--   price       采集当时的价格，用于事后核对「当时溢价是多少」
--
-- UNIQUE(instrument_id, trade_date) 让「盘中反复刷新」与「晚间补写净值」落在同一行，
-- 既不产生重复记录，也不丢掉当天已经采到的 IOPV。
CREATE TABLE fund_reference (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id BIGINT NOT NULL REFERENCES instrument(id),
    trade_date    DATE        NOT NULL,
    nav           NUMERIC(18, 6),
    nav_date      DATE,
    iopv          NUMERIC(18, 6),
    iopv_time     TIMESTAMPTZ,
    price         NUMERIC(18, 6),
    -- 两个来源分开记：一行里 IOPV/价格来自腾讯，净值来自天天基金，用一列表达必然要说谎
    market_source_code VARCHAR(32),
    nav_source_code    VARCHAR(32),
    fetched_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_fund_reference UNIQUE (instrument_id, trade_date),
    -- 非正价格/净值一律拒写：负净值是脏数据，0 会把溢价算成无穷大
    CONSTRAINT ck_fund_reference_positive CHECK (
        (nav IS NULL OR nav > 0)
        AND (iopv IS NULL OR iopv > 0)
        AND (price IS NULL OR price > 0)
    ),
    -- 空行没有意义：至少要有价格或 IOPV 或净值其中之一
    CONSTRAINT ck_fund_reference_has_value CHECK (nav IS NOT NULL OR iopv IS NOT NULL OR price IS NOT NULL)
);

CREATE INDEX idx_fund_reference_instrument_date ON fund_reference (instrument_id, trade_date DESC);

COMMENT ON TABLE fund_reference IS 'ETF/LOF 的 IOPV 与单位净值快照（P1.4），溢价率在查询层计算，不落库';
COMMENT ON COLUMN fund_reference.trade_date IS '行情日期；净值补写行的 trade_date 等于 nav_date';
COMMENT ON COLUMN fund_reference.nav_date IS '净值所属日期，与 trade_date 的差即净值的滞后天数';
COMMENT ON COLUMN fund_reference.market_source_code IS '价格/IOPV 来源（tencent-qt）';
COMMENT ON COLUMN fund_reference.nav_source_code IS '净值来源（eastmoney-f10-lsjz）';
