-- V9：资料库（P3.1）
--
-- 为什么新建一组表而不是复用日记：日记是"我自己写的"，资料是"别人写的、我存下来的"。
-- 两者都要检索，但资料的来源、时间、去重语义完全不同——日记重复写一篇是用户的自由，
-- 资料重复存一篇是误操作，必须拦住。放在一起会让两种语义互相污染。
--
-- 为什么切片单独一张表：检索的最小单位是段落而不是整篇。
-- 一篇三万字的研报里命中一句话，返回整篇等于没检索。切片带 char_start/char_end，
-- 引用才能回到原文的确切位置（P3 验收里"引用可追溯"靠的就是这两个字段）。
--
-- 为什么 content_hash 要唯一：同一篇资料粘两次是最常见的误操作。
-- 冲突时接口返回 409 并给出已存在的文档 id，让用户跳过去，而不是悄悄存两份。

CREATE TABLE library_document (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        TEXT        NOT NULL,
    source_type  VARCHAR(16) NOT NULL,
    source_ref   TEXT,
    publisher    TEXT,
    -- 用 DATE 而不是 TIMESTAMPTZ：资料发布日期通常只到天，
    -- 存"某天 00:00 UTC"再按东八区显示会漂成前一天
    published_at DATE,
    imported_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    content      TEXT        NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    char_count   INT         NOT NULL,
    status       VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    note         TEXT,
    CONSTRAINT ck_library_document_source_type CHECK (source_type IN ('PASTE', 'FILE', 'URL')),
    CONSTRAINT ck_library_document_status CHECK (status IN ('ACTIVE', 'ARCHIVED'))
);

CREATE UNIQUE INDEX ux_library_document_hash ON library_document (content_hash);
CREATE INDEX ix_library_document_imported ON library_document (imported_at DESC);

CREATE TABLE library_chunk (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES library_document (id) ON DELETE CASCADE,
    seq         INT    NOT NULL,
    heading     TEXT,
    content     TEXT   NOT NULL,
    -- 在原文中的字符偏移（从 0 开始，左闭右开）。引用与高亮都靠它定位
    char_start  INT    NOT NULL,
    char_end    INT    NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (document_id, seq)
);

CREATE INDEX ix_library_chunk_document ON library_chunk (document_id);

-- 资料与标的的关联：手动维护，不做自动实体识别（误标比不标更糟）
CREATE TABLE library_document_instrument (
    document_id   BIGINT NOT NULL REFERENCES library_document (id) ON DELETE CASCADE,
    instrument_id BIGINT NOT NULL REFERENCES instrument (id),
    PRIMARY KEY (document_id, instrument_id)
);

COMMENT ON TABLE library_document IS '资料文档：一篇 = 一次导入（P3.1）';
COMMENT ON COLUMN library_document.source_type IS 'PASTE 粘贴 / FILE 本地文件 / URL 预留';
COMMENT ON COLUMN library_document.source_ref IS '文件名或 URL；粘贴时为空';
COMMENT ON COLUMN library_document.content IS '规范化后的全文（统一换行、压缩空行、去首尾空白）';
COMMENT ON COLUMN library_document.content_hash IS 'sha256(规范化正文)，用于拦截重复导入';
COMMENT ON TABLE library_chunk IS '资料片段：检索与引用的最小单位';
COMMENT ON COLUMN library_chunk.char_start IS '片段在原文中的起始字符偏移（左闭）';
COMMENT ON COLUMN library_chunk.char_end IS '片段在原文中的结束字符偏移（右开）';
