-- V4: P1 历史日 K 线（对应 docs/DATABASE.md §4 kline 的精简实现）
-- D3 决策：P1 只做日线，表名直接叫 kline_daily，不引入 interval_code 多周期维度。
-- D4 决策：adjust 参与唯一键。前复权的历史值会随除权「整体移动」，
--          所以同步必须 UPSERT 覆盖，不能只做增量 INSERT。
-- 数据来源：Python 适配器（GET /internal/v1/kline），Java 负责校验与落库。

CREATE TABLE kline_daily (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id  BIGINT NOT NULL REFERENCES instrument(id),
    trade_date     DATE   NOT NULL,
    adjust         VARCHAR(8) NOT NULL,            -- qfq / hfq / raw
    open           NUMERIC(20, 6) NOT NULL,
    high           NUMERIC(20, 6) NOT NULL,
    low            NUMERIC(20, 6) NOT NULL,
    close          NUMERIC(20, 6) NOT NULL,
    volume         NUMERIC(24, 4),                 -- 上游单位：手
    amount         NUMERIC(24, 4),                 -- 上游单位：元
    change_percent NUMERIC(12, 6),                 -- 百分数值: 1.12 = 1.12%
    turnover_rate  NUMERIC(12, 6),                 -- 百分数值
    source_code    VARCHAR(32) NOT NULL,
    fetched_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_kline_daily UNIQUE (instrument_id, trade_date, adjust),
    -- 前复权长窗口会把早期价格算成负数（实测茅台 2001-08-27 为 -312.68）。
    -- Java 侧已先行拦截，这里再兜一层，避免脏数据落库。
    CONSTRAINT ck_kline_daily_positive CHECK (open > 0 AND high > 0 AND low > 0 AND close > 0),
    CONSTRAINT ck_kline_daily_ohlc CHECK (high >= low)
);

CREATE INDEX idx_kline_daily_lookup ON kline_daily (instrument_id, adjust, trade_date DESC);
