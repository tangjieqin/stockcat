-- V1__init.sql: P0 核心表（对应 docs/DATABASE.md §3）
-- 通用约定: BIGINT IDENTITY 主键; 财务值 NUMERIC; 时间 TIMESTAMPTZ (UTC)

-- 3.1 标的主数据
CREATE TABLE instrument (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market         VARCHAR(16)  NOT NULL,
    symbol         VARCHAR(32)  NOT NULL,
    name           VARCHAR(128) NOT NULL,
    instrument_type VARCHAR(16) NOT NULL,          -- STOCK / ETF / LOF
    currency       CHAR(3)      NOT NULL DEFAULT 'CNY',
    source_code    VARCHAR(32),
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_instrument_market_symbol UNIQUE (market, symbol)
);

-- 3.2 自选列表（P0 单用户）
CREATE TABLE watchlist_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id BIGINT NOT NULL REFERENCES instrument(id),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_watchlist_instrument UNIQUE (instrument_id)
);

-- 3.3 行情快照
CREATE TABLE quote_snapshot (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id   BIGINT NOT NULL REFERENCES instrument(id),
    source_code     VARCHAR(32) NOT NULL,
    last_price      NUMERIC(20, 6),
    previous_close  NUMERIC(20, 6),
    change_percent  NUMERIC(12, 6),                -- 百分数值: 2.5 = 2.5%
    volume          NUMERIC(24, 4),
    turnover        NUMERIC(24, 4),
    market_time     TIMESTAMPTZ,                   -- 数据源行情时间
    collected_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    data_status     VARCHAR(16) NOT NULL,          -- VALID / STALE / PARTIAL / INVALID
    raw_payload     JSONB
);
CREATE INDEX idx_quote_instrument_time ON quote_snapshot (instrument_id, collected_at DESC);
CREATE INDEX idx_quote_collected_time  ON quote_snapshot (collected_at DESC);

-- 3.4 交易日历（P0 仅 A 股）
CREATE TABLE trading_calendar (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market         VARCHAR(16) NOT NULL,
    trade_date     DATE        NOT NULL,
    is_trading_day BOOLEAN     NOT NULL,
    session_json   JSONB,
    source_code    VARCHAR(32),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_calendar_market_date UNIQUE (market, trade_date)
);

-- 3.5 告警规则（同一标的可挂多条，rule_type 可插拔 + params JSONB）
CREATE TABLE alert_rule (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(128) NOT NULL,
    instrument_id     BIGINT NOT NULL REFERENCES instrument(id),
    rule_type         VARCHAR(32) NOT NULL,        -- P0: PRICE_ABOVE/BELOW, CHANGE_PERCENT_ABOVE/BELOW
    params            JSONB     NOT NULL,          -- 结构由 rule_type 决定
    cooldown_minutes  INTEGER   NOT NULL DEFAULT 30,
    enabled           BOOLEAN   NOT NULL DEFAULT TRUE,
    last_triggered_at TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_rule_enabled_instrument ON alert_rule (enabled, instrument_id);

-- 3.6 告警事件（快照字段保留规则上下文）
CREATE TABLE alert_event (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id                   BIGINT,             -- 规则删除后置空
    instrument_id             BIGINT NOT NULL REFERENCES instrument(id),
    rule_name_snapshot        VARCHAR(128) NOT NULL,
    rule_type_snapshot        VARCHAR(32)  NOT NULL,
    condition_params_snapshot JSONB        NOT NULL,
    observed_price            NUMERIC(20, 6),
    observed_change_percent   NUMERIC(12, 6),
    observed_detail           JSONB,
    quote_market_time         TIMESTAMPTZ,
    triggered_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    deduplication_key         VARCHAR(160) NOT NULL,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_alert_event_dedup UNIQUE (deduplication_key)
);
CREATE INDEX idx_event_triggered    ON alert_event (triggered_at DESC);
CREATE INDEX idx_event_instrument_t ON alert_event (instrument_id, triggered_at DESC);

-- 3.7 通知记录
CREATE TABLE notification_record (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_event_id      BIGINT NOT NULL REFERENCES alert_event(id),
    channel             VARCHAR(24) NOT NULL,      -- EMAIL / SERVERCHAN / PUSHPLUS
    status              VARCHAR(16) NOT NULL,      -- PENDING / SENT / FAILED
    provider_message_id VARCHAR(128),
    attempt_count       INTEGER     NOT NULL DEFAULT 0,
    last_error_code     VARCHAR(64),
    last_error_message  VARCHAR(512),              -- 不得包含密钥
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at             TIMESTAMPTZ
);
CREATE INDEX idx_notif_event  ON notification_record (alert_event_id);
CREATE INDEX idx_notif_status ON notification_record (status, created_at);

-- 3.8 监控标的集合（决定采集与评估范围，独立于自选）
CREATE TABLE monitor_target (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id BIGINT NOT NULL REFERENCES instrument(id),
    enabled       BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_monitor_instrument UNIQUE (instrument_id)
);

-- 3.9 交易流水（持仓由此表实时聚合，不建持仓表）
CREATE TABLE trade_record (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id BIGINT NOT NULL REFERENCES instrument(id),
    direction     VARCHAR(8)  NOT NULL,            -- BUY / SELL
    price         NUMERIC(20, 6) NOT NULL,         -- > 0
    quantity      NUMERIC(24, 4) NOT NULL,         -- > 0
    fee           NUMERIC(20, 6) NOT NULL DEFAULT 0,
    trade_time    TIMESTAMPTZ NOT NULL,
    note          VARCHAR(512),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_trade_instrument_time ON trade_record (instrument_id, trade_time);
CREATE INDEX idx_trade_time            ON trade_record (trade_time DESC);

-- 3.11 市场复盘（每交易日一篇）
CREATE TABLE market_recap (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recap_date              DATE        NOT NULL,
    title                   VARCHAR(128) NOT NULL,
    market_summary          TEXT,                -- 市场主要情况（结构化提示字段）
    sector_notes            TEXT,                -- 板块表现记录
    content                 TEXT        NOT NULL, -- 完整正文 Markdown
    related_alert_event_ids JSONB,
    status                  VARCHAR(16) NOT NULL DEFAULT 'MANUAL',  -- MANUAL / AI_DRAFT
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_recap_date UNIQUE (recap_date)
);
CREATE INDEX idx_recap_date ON market_recap (recap_date DESC);

-- 3.12 我的日记（树状笔记本: FOLDER/DOC 统一一棵树）
CREATE TABLE diary_node (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id               BIGINT REFERENCES diary_node(id),   -- NULL 为根级
    node_type               VARCHAR(8)   NOT NULL,  -- FOLDER / DOC
    title                   VARCHAR(128) NOT NULL,
    content                 TEXT,                    -- 仅 DOC 有; FOLDER 恒 NULL
    related_instrument_ids  JSONB,
    sort_order              INTEGER      NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_diary_parent_sort ON diary_node (parent_id, sort_order);
